// Bringing papers up to date (daemon/lib/catchup.mjs): prompt versions, what a note says made it, and what's to do.
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

const U = () => import("../daemon/lib/catchup.mjs");
const T = () => import("../daemon/lib/taxonomies.mjs");

const prompt = (over) => Object.assign({ id: "findings", title: "Findings", model: "default", effort: "high", output: "note", brief: true, body: "Summarize." }, over || {});

test("a prompt's version: its text, what it makes and its brief decide it, not its title, model or effort", async () => {
  const { promptFingerprint } = await U();
  const h = promptFingerprint(prompt());
  assert.match(h, /^[0-9a-f]{12}$/);
  assert.equal(promptFingerprint(prompt({ title: "Other", model: "claude:opus", effort: "low", body: "  Summarize.\n" })), h);
  assert.notEqual(promptFingerprint(prompt({ body: "Summarize briefly." })), h);
  assert.notEqual(promptFingerprint(prompt({ output: "concept-map" })), h);
  assert.equal(promptFingerprint(prompt({ brief: false })), h); // a note has no brief
  assert.notEqual(promptFingerprint(prompt({ output: "concept-map", brief: false })), promptFingerprint(prompt({ output: "concept-map" })));
});

test("version numbers: each new text that writes a note the next one, an old text its own again; kept in a file", async () => {
  const { versionOf, versionsFor, loadVersions } = await U();
  const reg = { prompts: {} };
  const use = { use: true };
  assert.deepEqual([versionOf(reg, prompt(), new Date(), use).n, versionOf(reg, prompt(), new Date(), use).changed], [1, false]);
  assert.equal(versionOf(reg, prompt({ body: "New." }), new Date(), use).n, 2);
  assert.equal(versionOf(reg, prompt(), new Date(), use).n, 1); // back to the first text
  const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "oma-versions-")), "v.json");
  const run = { save: true, use: true };
  assert.equal(versionsFor([prompt()], file, run).get("findings").n, 1);
  assert.equal(versionsFor([prompt({ body: "New." })], file, run).get("findings").n, 2);
  assert.equal(loadVersions(file).prompts.findings.length, 2);
});

test("version numbers: a text only listed takes none (a new prompt's placeholder, an edit on the way)", async () => {
  const { versionsFor, loadVersions } = await U();
  const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "oma-versions-")), "v.json");
  assert.equal(versionsFor([prompt({ body: "Write your prompt here." })], file).get("findings").n, 1); // listed
  assert.equal(fs.existsSync(file), false); // listing writes nothing
  versionsFor([prompt({ body: "Draft." })], file, { save: true }); // saved, never used
  assert.equal(versionsFor([prompt({ body: "Summarize." })], file, { save: true, use: true }).get("findings").n, 1); // the first note: v1
  assert.equal(versionsFor([prompt({ body: "Summarize more." })], file, { save: true, use: true }).get("findings").n, 2);
  assert.ok(loadVersions(file).prompts.findings.filter((v) => v.used).every((v) => v.n <= 2));
});

test("version numbers: the notes, from any machine, say which numbers are taken", async () => {
  const { versionOf, promptNotes } = await U();
  const h = (body) => (versionOf({ prompts: {} }, prompt({ body })).hash);
  const notes = [
    { libraryID: 1, parentKey: "PAPER001", generated: `Generated by Claude (opus) with the “Findings” prompt, version 3 (findings@${h("Summarize.")}), on 2026-10-01.` },
    { libraryID: 1, parentKey: "PAPER001", generated: `Generated by Claude (opus) with the “Findings” prompt, version 3 (findings@${h("Summarize.")}), on 2026-10-02.` },
    { libraryID: 1, parentKey: "PAPER002", generated: `Generated by Claude (opus) with the “Findings” prompt, version 5 (findings@${h("Other.")}), on 2026-10-03.` },
    { libraryID: 1, parentKey: "PAPER002", generated: "Generated by Claude (opus) with the “Theory” prompt, version 9 (theory@0123456789ab), on 2026-10-03." },
  ];
  const { seen, runs } = promptNotes(notes, "findings");
  assert.deepEqual(seen.map((v) => v.n), [3, 5]);
  assert.equal(runs.get("1:PAPER001@" + h("Summarize.")), 2);
  const fresh = { prompts: {} }; // another machine: nothing of its own
  assert.equal(versionOf(fresh, prompt(), new Date(), { seen, use: true }).n, 3); // the notes' number for this text
  assert.equal(versionOf(fresh, prompt({ body: "Third." }), new Date(), { seen, use: true }).n, 6); // after every number taken
  const mine = { prompts: { findings: [{ n: 5, hash: h("Mine."), used: true }] } }; // 5 is taken elsewhere by another text
  assert.equal(versionOf(mine, prompt({ body: "Mine." }), new Date(), { seen, use: true }).n, 6);
});

test("what a note says made it: the prompt, its version and hash; older notes only the title", async () => {
  const { parseGenerated } = await U();
  assert.deepEqual(parseGenerated("Generated by Claude (opus) with the “Findings” prompt, version 2 (findings@3f2a91c0b1d2), on 2026-10-04. Check quotes."),
    { promptId: "findings", hash: "3f2a91c0b1d2", n: 2, title: "Findings" });
  assert.deepEqual(parseGenerated("Generated by Claude (opus) with the “Findings” prompt on 2026-01-02."), { promptId: "", hash: "", n: 0, title: "Findings" });
  assert.deepEqual(parseGenerated(""), { promptId: "", hash: "", n: 0, title: "" });
});

test("runs: the latest per paper and prompt, from notes and artifacts; older ones stale, unknown ones left alone", async () => {
  const { promptRuns, stalePromptJobs, recentJobs, paperCount } = await U();
  const prompts = [prompt(), prompt({ id: "map", title: "Map", output: "concept-map" })];
  const gen = (v, h) => `Generated by X (y) with the “Findings” prompt, version ${v} (findings@${h}), on 2026-10-01.`;
  const notes = [
    { libraryID: 1, parentKey: "AAAAAAAA", dateAdded: "2026-01-01 00:00:00", generated: gen(1, "aaaaaaaaaaaa") },
    { libraryID: 1, parentKey: "AAAAAAAA", dateAdded: "2026-02-01 00:00:00", generated: gen(2, "bbbbbbbbbbbb") }, // its latest
    { libraryID: 1, parentKey: "BBBBBBBB", dateAdded: "2026-01-01 00:00:00", generated: gen(1, "aaaaaaaaaaaa") },
    { libraryID: 1, parentKey: "CCCCCCCC", dateAdded: "2025-01-01 00:00:00", generated: "Generated by X with the “Findings” prompt on 2025-01-01." },
    { libraryID: 1, parentKey: "", generated: gen(1, "aaaaaaaaaaaa") },
  ];
  const artifacts = [{ key: "BBBBBBBB", libraryID: 1, promptMade: { id: "map", hash: "cccccccccccc", at: "2026-03-01T00:00:00Z" } }, { key: "DDDDDDDD", libraryID: 1, promptMade: null }];
  const runs = promptRuns(notes, artifacts, prompts);
  assert.deepEqual(runs["1:AAAAAAAA"], { findings: { hash: "bbbbbbbbbbbb", at: "2026-02-01 00:00:00" } });
  assert.equal(runs["1:CCCCCCCC"].findings.hash, ""); // matched by its title
  assert.equal(runs["1:BBBBBBBB"].map.hash, "cccccccccccc");
  const versions = new Map([["findings", { n: 2, hash: "bbbbbbbbbbbb" }], ["map", { n: 1, hash: "dddddddddddd" }]]);
  const s = stalePromptJobs(runs, versions);
  assert.deepEqual(s.jobs.map((j) => [j.id, j.prompt]).sort(), [["1:BBBBBBBB", "findings"], ["1:BBBBBBBB", "map"]]);
  assert.equal(s.unknown, 1);
  assert.equal(paperCount(s.jobs), 1);
  // the last days: never run, or an older version; a run before versions were kept counts as done
  const papers = [{ key: "AAAAAAAA", libraryID: 1, title: "A" }, { key: "BBBBBBBB", libraryID: 1, title: "B" }, { key: "CCCCCCCC", libraryID: 1, title: "C" }, { key: "EEEEEEEE", libraryID: 1, title: "E" }];
  const jobs = recentJobs(papers, { prompts: ["findings"], runs, versions, extract: true, textless: ["1:EEEEEEEE"] });
  assert.deepEqual(jobs.map((j) => [j.id, j.op]), [["1:BBBBBBBB", "prompt"], ["1:EEEEEEEE", "extract"], ["1:EEEEEEEE", "prompt"]]);
});

test("taxonomies: papers tagged by an older version, and the last days' papers never tagged (by the ones they miss)", async () => {
  const { staleTaxonomyJobs, recentJobs } = await U();
  const { fingerprint } = await T();
  const a = { id: "method", prefix: "method/", kind: "one", question: "q", labels: [{ name: "survey", definition: "" }] };
  const b = { id: "type", prefix: "type/", kind: "one", question: "q", labels: [{ name: "case", definition: "" }] };
  const store = { papers: {
    "1:AAAAAAAA": { taxonomies: { method: { hash: fingerprint(a), probs: {} }, type: { hash: fingerprint(b), probs: {} } } },
    "1:BBBBBBBB": { taxonomies: { method: { hash: "old", probs: {} }, type: { hash: fingerprint(b), probs: {} } } },
  } };
  assert.deepEqual(staleTaxonomyJobs(store, [a, b]), [{ id: "1:BBBBBBBB", op: "classify", only: ["method"] }]);
  const papers = [{ key: "AAAAAAAA", libraryID: 1 }, { key: "BBBBBBBB", libraryID: 1 }, { key: "CCCCCCCC", libraryID: 1 }];
  const jobs = recentJobs(papers, { tag: true, store, taxonomies: [a, b] });
  assert.deepEqual(jobs.map((j) => [j.id, j.only || "all"]), [["1:BBBBBBBB", ["method"]], ["1:CCCCCCCC", "all"]]);
  assert.deepEqual(recentJobs(papers, { tag: false, store, taxonomies: [a, b] }), []);
});

test("version numbers: a file from before `used` was kept, and the notes unread or read", async () => {
  const { versionOf, promptNotes } = await U();
  const h = (body) => versionOf({ prompts: {} }, prompt({ body })).hash;
  const legacy = () => ({ prompts: { findings: [{ n: 1, hash: h("Write your prompt here.") }, { n: 2, hash: h("Draft.") }, { n: 3, hash: h("Summarize.") }] } });
  // the notes couldn't be read (a time out): this machine's numbers stand, nothing renumbered
  assert.equal(versionOf(legacy(), prompt(), new Date(), { seen: [], seenOk: false, use: true }).n, 3);
  assert.equal(versionOf(legacy(), prompt({ body: "New." }), new Date(), { seen: [], seenOk: false, use: true }).n, 4);
  // read: the notes say what was taken (v3); the numbers only listed (1, 2) don't count
  const seen = [{ n: 3, hash: h("Summarize.") }];
  assert.equal(versionOf(legacy(), prompt(), new Date(), { seen, seenOk: true, use: true }).n, 3);
  assert.equal(versionOf(legacy(), prompt({ body: "New." }), new Date(), { seen, seenOk: true, use: true }).n, 4);
  // one text, two numbers (two machines apart): the smallest, whatever the order
  const line = (n) => ({ libraryID: 1, parentKey: "PAPER001", generated: `Generated by X (y) with the “Findings” prompt, version ${n} (findings@${h("Summarize.")}), on 2026-10-01.` });
  assert.deepEqual(promptNotes([line(3), line(1)], "findings").seen, [{ n: 1, hash: h("Summarize.") }]);
  assert.deepEqual(promptNotes([line(1), line(3)], "findings").seen, [{ n: 1, hash: h("Summarize.") }]);
});
